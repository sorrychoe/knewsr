test_that("as_dtm builds sparse matrices with the requested weight", {
  tk <- toy_tokens()
  dtm <- as_dtm(tk)
  expect_s4_class(dtm, "dgCMatrix")
  expect_equal(dimnames(dtm), list(c("1", "2", "3"), c("x", "y", "z")))
  expect_equal(dtm["1", "x"], 2)
  expect_equal(max(as_dtm(tk, "binary")), 1)
  expect_equal(as_dtm(tk, "tfidf")["1", "x"], 2 / 3 * log(3 / 2))
  expect_equal(as.matrix(as_tdm(tk)), t(as.matrix(dtm)))
  expect_error(as_dtm(tk, "bogus"))
})

test_that("cooccurrence counts documents or windows", {
  tk <- toy_tokens()
  doc <- cooccurrence(tk)
  expect_equal(doc$n[doc$term1 == "x" & doc$term2 == "y"], 1)
  expect_equal(doc$n[doc$term1 == "x" & doc$term2 == "z"], 1)
  m <- cooccurrence(tk, output = "matrix")
  expect_true(Matrix::isSymmetric(m))
  expect_equal(unname(Matrix::diag(m)), c(0, 0, 0))
  win <- cooccurrence(tk, window = 1)
  # pairs: x-y, y-x (doc 1) and x-z (doc 2)
  expect_equal(win$n[win$term1 == "x" & win$term2 == "y"], 2)
  expect_equal(win$n[win$term1 == "x" & win$term2 == "z"], 1)
  expect_equal(nrow(cooccurrence(tk, top_n = 2)), 1)
  expect_error(cooccurrence(tk, window = "sentence"), "window")
})
